"""Compare ts_rank and BM25 as the lexical side of hybrid search.

Experiment only: BM25 runs in memory over every case, and bm25s and PyStemmer are not
project dependencies. Run from the repository root with:

    uv run --with bm25s --with PyStemmer python -m mechragnic.eval.bm25_experiment

Add --agent-queries to search with the queries the agent writes (agent_queries.json,
generated by mechragnic.eval.agent_queries) instead of the users' questions, or --split
to give the vector search the user's question and the lexical search the agent's query.
"""

import asyncio
import json
import logging
import sys
from collections.abc import Awaitable, Callable
from functools import partial

import bm25s
import Stemmer

from mechragnic.clients.ollama import create_embedding
from mechragnic.database.cases import get_cases_by_ids_ordered, search_by_embedding, search_by_keywords
from mechragnic.database.connection import connect
from mechragnic.eval.agent_queries import QUERIES_FILE
from mechragnic.eval.run import TOP_K, evaluate, load_cases
from mechragnic.retrieval.search import CANDIDATES, reciprocal_rank_fusion

logging.getLogger("httpx").setLevel(logging.WARNING)

# 1.0 is vector only, 0.0 is lexical only
ALPHAS = [1.0, 0.9, 0.8, 0.7, 0.6, 0.5, 0.0]

LexicalSearch = Callable[[str, int], Awaitable[list[int]]]

# Each question is embedded once and reused across every configuration
_embeddings: dict[str, list[float]] = {}


async def embed(query: str) -> list[float]:
    if query not in _embeddings:
        _embeddings[query] = await create_embedding(query)
    return _embeddings[query]


class Bm25Index:
    def __init__(self, case_ids: list[int], texts: list[str]):
        self.case_ids = case_ids
        self.stemmer = Stemmer.Stemmer("english")
        self.retriever = bm25s.BM25()
        tokens = bm25s.tokenize(texts, stopwords="en", stemmer=self.stemmer, show_progress=False)
        self.retriever.index(tokens, show_progress=False)

    async def search(self, query: str, limit: int) -> list[int]:
        query_tokens = bm25s.tokenize([query], stopwords="en", stemmer=self.stemmer, show_progress=False)
        positions, _ = self.retriever.retrieve(query_tokens, k=limit, show_progress=False)
        # retrieve returns positions in the indexed list, not case ids
        return [self.case_ids[position] for position in positions[0]]


async def load_bm25_index() -> Bm25Index:
    connection = await connect()
    try:
        # Same text as the search_text tsvector column: symptoms and causes
        rows = await connection.fetch(
            "SELECT id, join_text(symptoms) || ' ' || join_text(causes) AS text FROM mechanic_cases ORDER BY id"
        )
    finally:
        await connection.close()
    return Bm25Index([row["id"] for row in rows], [row["text"] for row in rows])


async def hybrid_search(
    query: str,
    top_k: int,
    alpha: float,
    lexical: LexicalSearch,
    lexical_queries: dict[str, str] | None = None,
) -> list[dict]:
    # With lexical_queries, the vector search keeps the query it was given and the
    # lexical search uses the mapped one instead
    lexical_query = lexical_queries[query] if lexical_queries else query
    embedding = await embed(query)
    vector_ids = [case["id"] for case in await search_by_embedding(embedding, CANDIDATES)]
    lexical_ids = await lexical(lexical_query, CANDIDATES)
    fused_ids = reciprocal_rank_fusion([vector_ids, lexical_ids], [alpha, 1 - alpha])[:top_k]
    return await get_cases_by_ids_ordered(fused_ids, embedding)


async def main():
    cases = load_cases()
    lexical_queries: dict[str, str] | None = None
    if "--agent-queries" in sys.argv:
        queries = json.loads(QUERIES_FILE.read_text())
        # Same expected cases, searched with the agent's query instead of the question
        cases = [case.model_copy(update={"question": queries[case.question]}) for case in cases]
        print("Searching with the agent's queries\n")
    elif "--split" in sys.argv:
        lexical_queries = json.loads(QUERIES_FILE.read_text())
        print("Vector search with the users' questions, lexical search with the agent's queries\n")
    else:
        print("Searching with the users' questions\n")

    bm25_index = await load_bm25_index()
    lexical_searches: dict[str, LexicalSearch] = {
        "ts_rank": search_by_keywords,
        "bm25": bm25_index.search,
    }

    print(f"{'alpha':>5}  {'lexical':<8} recall@{TOP_K}    MRR")
    for alpha in ALPHAS:
        for name, lexical in lexical_searches.items():
            search = partial(hybrid_search, alpha=alpha, lexical=lexical, lexical_queries=lexical_queries)
            recall, mrr, _ = await evaluate(cases, search)
            print(f"{alpha:>5.1f}  {name:<8} {recall:>8.3f}  {mrr:.3f}")


if __name__ == "__main__":
    asyncio.run(main())
